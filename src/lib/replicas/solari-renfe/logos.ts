/** The flap the plate is printed on, pale against the black ones beside it. */
export const PLATE = '#efece1';
/** The grey the product names are printed in, from Renfe's own artwork. */
const NAME_GREY = '#76777b';
/** The two inks of the identity of 2026, read off the plates ADIF's own boards print. */
const NEO_NAVY = '#00132a';
const NEO_PURPLE = '#5b064b';

/** From the plate's edges to the ink. */
const MARGIN = { side: 1.2, top: 1.1 };
/** Between a mark and the name beside it. */
const GAP = 1.4;

export type Logo = (x: number, y: number, width: number) => VNode[];

/** The Renfe plate: the wordmark adopted in 2005, and the product beside it. */
function renfe(name: string): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    const left = x + MARGIN.side;
    const room = width - 2 * MARGIN.side;
    const markHeight = (FLAP.height - 2 * MARGIN.top) * 0.78;
    const markWidth = widthOf(RENFE, markHeight);
    const nameX = left + markWidth + GAP;
    return [
      place(RENFE, left, cy, markHeight),
      ...nameNodes(name, nameX, cy, Math.max(0, left + room - nameX), markHeight * 0.62, SANS, NAME_GREY),
    ];
  };
}

/**
 * The Regionales plate: the «R» and the product beside it in the same orange,
 * set upright in capitals as the identity's own artwork sets it.
 */
function regionales(name: string): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    const left = x + MARGIN.side;
    const room = width - 2 * MARGIN.side;
    const markHeight = (FLAP.height - 2 * MARGIN.top) * 0.74;
    const nameX = left + widthOf(REGIONALES, markHeight) + GAP;
    return [
      place(REGIONALES, left, cy, markHeight),
      ...nameNodes(name.toUpperCase(), nameX, cy, Math.max(0, left + room - nameX), markHeight * 0.46, SANS, '#ff6720', false),
    ];
  };
}

/** The Grandes Líneas plate the 2007 photograph still shows: the two strokes, and the product beside them. */
function grandesLineas(name: string): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    const left = x + MARGIN.side;
    const room = width - 2 * MARGIN.side;
    const markHeight = (FLAP.height - 2 * MARGIN.top) * 0.74;
    const nameX = left + widthOf(SWOOSH, markHeight) + GAP;
    return [
      place(SWOOSH, left, cy, markHeight),
      ...nameNodes(name, nameX, cy, Math.max(0, left + room - nameX), markHeight * 0.52, SERIF, NAME_GREY),
    ];
  };
}

/**
 * The identity Renfe adopted in 2026: the new mark, and the product beside it
 * inside a stadium, in the navy of the high-speed family or the purple of the
 * rest. ADIF's boards print these; its own code says the artwork is still
 * only raster, so the mark here is Renfe's vector and the name is set in type.
 */
function neo(name: string, ink: string): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    const left = x + MARGIN.side;
    const markHeight = (FLAP.height - 2 * MARGIN.top) * 0.82;
    const boxLeft = left + widthOf(NEOGALLETA, markHeight) + GAP * 0.7;
    const boxRight = x + width - MARGIN.side;
    const boxHeight = markHeight * 0.78;
    const cap = boxHeight * 0.52;
    const size = cap / CAP;
    const room = boxRight - boxLeft - boxHeight;
    return [
      place(NEOGALLETA, left, cy, markHeight, ink),
      h('rect', {
        x: boxLeft, y: cy - boxHeight / 2, width: Math.max(0, boxRight - boxLeft), height: boxHeight,
        rx: boxHeight / 2, fill: 'none', stroke: ink, 'stroke-width': 0.3,
      }),
      h('text', {
        x: (boxLeft + boxRight) / 2, y: cy + cap / 2, 'font-family': SANS, 'font-size': size, 'text-anchor': 'middle',
        textLength: Math.min(room, advance(name) * size), lengthAdjust: 'spacingAndGlyphs', fill: ink,
      }, [name]),
    ];
  };
}

/** The plates of that identity printed white out of a coloured ground, as Alvia's and Media Distancia's are. */
function neoGround(name: string, ground: string): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    const left = x + MARGIN.side;
    const markHeight = (FLAP.height - 2 * MARGIN.top) * 0.6;
    const nameX = left + widthOf(NEORENFE, markHeight) + GAP;
    return [
      h('rect', { x, y, width, height: FLAP.height, rx: 0.4, fill: ground }),
      place(NEORENFE, left, cy, markHeight, '#ffffff'),
      ...nameNodes(name, nameX, cy, Math.max(0, x + width - MARGIN.side - nameX), markHeight * 0.68, SANS, '#ffffff'),
    ];
  };
}

/** Cercanías of that identity: the mark and the C, white out of the red ground. */
function neoCercanias(): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    // The two marks all but touch, as they are drawn joined on ADIF's boards.
    const markHeight = (FLAP.height - 2 * MARGIN.top) * 0.95;
    const gap = markHeight * 0.06;
    const together = widthOf(NEOGALLETA, markHeight) + gap + widthOf(CERCANIAS_C, markHeight);
    const left = x + (width - together) / 2;
    return [
      h('rect', { x, y, width, height: FLAP.height, rx: 0.4, fill: '#f4323f' }),
      place(CERCANIAS_C, left, cy, markHeight, '#ffffff'),
      place(NEOGALLETA, left + widthOf(CERCANIAS_C, markHeight) + gap, cy, markHeight, '#ffffff'),
    ];
  };
}

/**
 * A product with a wordmark of its own: that mark alone, centred on the
 * plate. It is not set beside the company's, which is the lockup for a
 * product named in lettering.
 */
function alone(art: Art, fraction: number): Logo {
  return (x, y, width) => {
    const cy = y + FLAP.height / 2;
    const height = (FLAP.height - 2 * MARGIN.top) * fraction;
    const room = width - 2 * MARGIN.side;
    const fitted = Math.min(height, room / (art.box.width / art.box.height));
    return [place(art, x + (width - widthOf(art, fitted)) / 2, cy, fitted)];
  };
}

