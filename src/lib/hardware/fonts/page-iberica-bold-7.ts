const GLYPHS = new Map<string, number[]>();
for (const [char, rows] of Object.entries({ ...RECONSTRUCTED, ...SEEN })) GLYPHS.set(char, fromRows(rows));

/** Which characters come from photographs, for the record. */
export const SEEN_IN_PHOTOGRAPHS: readonly string[] = Object.keys(SEEN);

export const pageIbericaBold7: ProportionalFont = {
  id: 'page-iberica-bold-7',
  rows: 7,
  spacing: 1,
  // Between "SIN" and "SERVICIO" there are about four blank columns.
  space: 2,
  glyph: (char) => GLYPHS.get(char),
  // Capitals only, accents dropped; the tilde of Ñ is kept.
  fold: (text) =>
    text
      .toUpperCase()
      .normalize('NFD')
      .replace(/[̀-̂̄-ͯ]/g, '')
      .normalize('NFC'),
};
