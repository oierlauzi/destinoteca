const WIDTH = 7;
const ROWS = 12;

/** A skeleton thickened one dot right and one dot down, as columns (bit 0 the top row). */
function thicken(skeleton: string): number[] {
  const rows = skeleton.split('/');
  const on = (r: number, c: number): boolean => rows[r]?.[c] === '#';
  const columns: number[] = [];
  for (let c = 0; c < WIDTH; c++) {
    let byte = 0;
    for (let r = 0; r < ROWS; r++) {
      if (on(r, c) || on(r - 1, c) || on(r, c - 1) || on(r - 1, c - 1)) byte |= 1 << r;
    }
    columns.push(byte);
  }
  return columns;
}

const GLYPHS = new Map<string, number[]>();
for (const [char, skeleton] of Object.entries(SKELETONS)) GLYPHS.set(char, thicken(skeleton));

export const pageIbericaLed12: ProportionalFont = {
  id: 'page-iberica-led-12',
  rows: ROWS,
  spacing: 1,
  // A space is one more character cell.
  space: WIDTH,
  glyph: (char) => GLYPHS.get(char),
  fold: (text) =>
    text
      .toUpperCase()
      .normalize('NFD')
      .replace(/[̀-̂̄-ͯ]/g, '')
      .normalize('NFC'),
};
