/** Rows of a glyph as they are written above, for tests. */
export function aegRows(char: string, face: 'large' | 'small'): string[] | undefined {
  if (face === 'small') return SMALL[char]?.split('/');
  const spec = LARGE[char];
  if (spec === undefined) return undefined;
  const [head, body] = spec.split('|');
  const rows = body!.split('/');
  const blank = '.'.repeat(rows[0]!.length);
  const all = [...Array.from({ length: Number(head) }, () => blank), ...rows];
  while (all.length < LARGE_ROWS) all.push(blank);
  return all;
}
