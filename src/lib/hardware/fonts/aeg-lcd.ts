/**
 * The two typefaces of AEG's liquid-crystal platform display of the AVE.
 *
 * The panel is one graphics matrix, not one glass per character, so the
 * controller could write at any size: the photographs show a large,
 * proportionally spaced face on the top line and a small fixed-pitch one on
 * the lines below, where seven characters fill the width of a module.
 *
 * Neither face can be read dot by dot: the photographs are a magazine
 * halftone and three press reproductions, and in none of them is a character
 * more than about twenty pixels tall. What is legible is the size of each
 * face against its module, that the strokes are one dot thick, that the top
 * line is proportional and has lower case, and that the lines below are
 * fixed-pitch capitals. The letters below are drawn to match that, not read:
 * SEEN lists the characters that can be made out in a photograph at all,
 * RECONSTRUCTED the rest.
 */

