#!/usr/bin/env python3
"""Writes src/lib/hardware/fonts/helvetica-metrics.ts from Liberation Sans.

Liberation Sans is metric-compatible with Arial, whose advance widths are
Helvetica's, so one table serves the whole stack the replicas name. Run:

    python3 tools/helvetica-metrics.py /usr/share/fonts/truetype/liberation2
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

CHARS = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xA0, 0x100)] + list('–—‘’‚“”„•…€')

OUT = Path(__file__).resolve().parent.parent / 'src/lib/hardware/fonts/helvetica-metrics.ts'


def widths(path: Path) -> str:
    font = TTFont(path)
    em = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    out = []
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        if glyph is None:
            continue
        out.append(round(hmtx[glyph][0] * 1000 / em))
    return ','.join(map(str, out))


def main() -> None:
    folder = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation2')
    chars = ''.join(CHARS).replace('\\', '\\\\').replace("'", "\\'")
    OUT.write_text(f"""// Generated by tools/helvetica-metrics.py from Liberation Sans: do not edit.

/** The characters the tables below measure, in order. */
export const CHARS = '{chars}';

/** Advance widths of Helvetica (and Arial, and Liberation Sans), in thousandths of the size. */
export const REGULAR = [{widths(folder / 'LiberationSans-Regular.ttf')}];

/** The same, bold. */
export const BOLD = [{widths(folder / 'LiberationSans-Bold.ttf')}];
""")


if __name__ == '__main__':
    main()
